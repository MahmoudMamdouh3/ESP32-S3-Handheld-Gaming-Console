"""Bundle simulator ES modules into a classic defer script for both http:// and file:// execution."""

from __future__ import annotations

import argparse
import posixpath
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SIM_DIR = REPO_ROOT / "simulator"
OUT_PATH = SIM_DIR / "bmo_simulator_app.js"

# Topological order across simulator/*.js and simulator/js/*.js (every import precedes its consumers).
MODULE_ORDER: tuple[str, ...] = (
    "./js/constants.js",
    "./js/hardware_layout_data.js",
    "./console_history_data.js",
    "./wasm_playtest_engine.js",
    "./js/internals_3d_data.js",
    "./js/internals_3d_board.js",
    "./js/internals_3d_mcu.js",
    "./bmo_internals_3d.js",
    "./js/console_3d_studio.js",
    "./js/console_3d_model.js",
    "./bmo_3d_console.js",
    "./js/museum_icons.js",
    "./js/museum.js",
    "./js/local_library_client.js",
    "./js/webserial.js",
    "./js/bmo_mode.js",
    "./js/internals.js",
    "./js/sim_controls.js",
    "./js/sim_screens.js",
    "./js/homebrew_demos.js",
    "./simulator.js",
)

_IMPORT_RE = re.compile(r"^import\s+\{([^}]+)\}\s+from\s+[\"']([^\"']+)[\"'];?\s*$", re.MULTILINE)
_EXPORT_DECL_RE = re.compile(r"^export\s+(?:async\s+)?(?:const|let|var|function|class)\s+([A-Za-z_$][A-Za-z0-9_$]*)", re.MULTILINE)
_EXPORT_PREFIX_RE = re.compile(r"^export\s+(?=(?:async\s+)?(?:const|let|var|function|class)\b)", re.MULTILINE)
_EXPORT_LIST_RE = re.compile(r"^export\s+\{([^}]+)\};?\s*$", re.MULTILINE)


def _resolve_module_id(importer_id: str, spec: str) -> str:
    base_dir = posixpath.dirname(importer_id.lstrip("./"))
    joined = posixpath.normpath(posixpath.join(base_dir, spec))
    return f"./{joined}"


def _transform_module(mod_id: str, source: str) -> str:
    exported_names: list[str] = []

    def _replace_import(match: re.Match[str]) -> str:
        bindings = " ".join(part.strip() for part in match.group(1).splitlines() if part.strip())
        target = _resolve_module_id(mod_id, match.group(2))
        if target not in MODULE_ORDER:
            raise RuntimeError(f"{mod_id}: unknown bundled import {target}")
        return f'const {{{bindings}}} = __require("{target}");'

    def _record_export_list(match: re.Match[str]) -> str:
        for item in match.group(1).split(","):
            name = item.strip()
            if name and name not in exported_names:
                exported_names.append(name)
        return ""

    transformed = _IMPORT_RE.sub(_replace_import, source.replace("\r\n", "\n"))
    # Remove Node-only ESM `import.meta` references so classic <script> execution never fails at parse time.
    transformed = re.sub(
        r"const \[\{ default: fsMod \}, \{ dirname, join \}, \{ fileURLToPath \}\] = await Promise\.all\(\[\s*import\(\"node:fs\"\),\s*import\(\"node:path\"\),\s*import\(\"node:url\"\),\s*\]\);\s*wasmBytes = fsMod\.readFileSync\(join\(dirname\(fileURLToPath\(import\.meta\.url\)\), \"bmo_playtest_cores\.wasm\"\)\);",
        'throw new Error("Node ESM fs loader unavailable in browser bundle");',
        transformed,
    )
    if "import.meta" in transformed:
        raise RuntimeError(f"{mod_id}: unsupported import.meta syntax in classic bundle")
    for decl_name in _EXPORT_DECL_RE.findall(transformed):
        if decl_name not in exported_names:
            exported_names.append(decl_name)
    transformed = _EXPORT_PREFIX_RE.sub("", transformed)
    transformed = _EXPORT_LIST_RE.sub(_record_export_list, transformed)
    if exported_names:
        transformed = transformed.rstrip() + f"\nObject.assign(__exports, {{ {', '.join(exported_names)} }});\n"
    return transformed


def build_bundle() -> str:
    sections = [
        "// GENERATED BY scripts/bundle_simulator.py - DO NOT EDIT BY HAND",
        "((global) => {",
        '  "use strict";',
        "  const __modules = {",
    ]
    for mod_id in MODULE_ORDER:
        mod_path = SIM_DIR / mod_id[2:]
        if not mod_path.is_file():
            raise FileNotFoundError(f"Missing simulator module: {mod_path}")
        body = _transform_module(mod_id, mod_path.read_text(encoding="utf-8"))
        indented = "\n".join(f"      {line}" if line else "" for line in body.splitlines())
        sections.append(f'    "{mod_id}": (__exports, __require) => {{\n{indented}\n    }},')
    sections.extend(
        [
            "  };",
            "  const __cache = {};",
            "  function __require(id) {",
            "    if (__cache[id]) return __cache[id].exports;",
            "    if (!Object.prototype.hasOwnProperty.call(__modules, id)) {",
            '      throw new Error("Unknown simulator module: " + id);',
            "    }",
            "    const mod = { exports: {} };",
            "    __cache[id] = mod;",
            "    __modules[id](mod.exports, __require);",
            "    return mod.exports;",
            "  }",
            '  const simMod = __require("./simulator.js");',
            "  global.BmoSimulator = simMod.BmoSimulator;",
            "})(typeof window !== \"undefined\" ? window : globalThis);",
            "",
        ]
    )
    return "\n".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Write simulator/bmo_simulator_app.js")
    mode.add_argument("--check", action="store_true", help="Fail if simulator/bmo_simulator_app.js is stale")
    args = parser.parse_args(argv)

    bundle = build_bundle()
    if args.check and not args.write:
        existing = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.is_file() else ""
        if existing != bundle:
            print(
                "Simulator bundle out of sync: simulator/bmo_simulator_app.js. Run `python scripts/bundle_simulator.py --write`.",
                file=sys.stderr,
            )
            return 1
        print(f"Simulator bundle sync clean ({len(MODULE_ORDER)} modules, {len(bundle):,} bytes).")
        return 0

    OUT_PATH.write_text(bundle, encoding="utf-8", newline="\n")
    print(f"Wrote simulator/bmo_simulator_app.js ({len(MODULE_ORDER)} modules, {len(bundle):,} bytes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
